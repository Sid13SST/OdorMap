"""Train and evaluate the fingerprint + logistic-regression baseline.

Writes results/baseline.md and saves models/baseline_lr.joblib (trained on
the full dataset, used by scripts/predict.py).
"""
from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr
from sklearn.metrics import f1_score, precision_score, recall_score, roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from odormap.data import REPO_ROOT, SMILES_COL, load_dataset  # noqa: E402
from odormap.features import N_BITS, RADIUS, featurize, murcko_scaffold  # noqa: E402
from odormap.inference import MODEL_PATH  # noqa: E402
from odormap.model import C, build_model, evaluate  # noqa: E402
from odormap.splits import iterative_stratified_kfold, scaffold_split  # noqa: E402
from odormap.train import fit_bundle, save_bundle  # noqa: E402

RESULTS = REPO_ROOT / "results" / "baseline.md"
METRICS = ["macro_roc_auc", "micro_roc_auc", "macro_f1@0.5", "mean_avg_precision"]


def fit_predict(X_tr, Y_tr, X_te):
    m = build_model()
    m.fit(X_tr, Y_tr)
    return m.predict_proba(X_te)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--folds", type=int, default=5)
    p.add_argument("--test-frac", type=float, default=0.2)
    args = p.parse_args(argv)

    t0 = time.time()
    df, labels = load_dataset()
    smiles = df[SMILES_COL].tolist()
    X = featurize(smiles)
    Y = df[labels].to_numpy()
    print(f"X {X.shape}, Y {Y.shape}")

    # (a) stratified random K-fold
    cv = []
    for k, (tr, te) in enumerate(iterative_stratified_kfold(Y, args.folds, args.seed)):
        r = evaluate(Y[te], fit_predict(X[tr], Y[tr], X[te]))
        r["n_train"], r["n_test"] = len(tr), len(te)
        cv.append(r)
        print(f"fold {k}: " + ", ".join(f"{m}={r[m]:.4f}" for m in METRICS))

    # (b) scaffold split
    tr, te = scaffold_split(smiles, args.test_frac, args.seed)
    S_te = fit_predict(X[tr], Y[tr], X[te])
    sc = evaluate(Y[te], S_te)
    print("scaffold: " + ", ".join(f"{m}={sc[m]:.4f}" for m in METRICS))
    tr_sc = {murcko_scaffold(smiles[i]) for i in tr}
    te_sc = {murcko_scaffold(smiles[i]) for i in te}
    assert not tr_sc & te_sc

    # Per-label F1 vs label frequency on the scaffold test set
    Yt, Pt = Y[te], (S_te >= 0.5).astype(int)
    f1_lab = f1_score(Yt, Pt, average=None, zero_division=0)
    pos_te, pos_tr = Yt.sum(axis=0), Y[tr].sum(axis=0)
    ok = (pos_te > 0) & (pos_te < len(te))
    auc_lab = np.array([roc_auc_score(Yt[:, j], S_te[:, j]) for j in np.where(ok)[0]])
    rho_te = spearmanr(f1_lab, pos_te)
    rho_tr = spearmanr(f1_lab, pos_tr)
    rho_auc = spearmanr(auc_lab, pos_te[ok])
    macro_p = precision_score(Yt, Pt, average="macro", zero_division=0)
    macro_r = recall_score(Yt, Pt, average="macro", zero_division=0)
    bands = [(1, 9), (10, 29), (30, None)]

    # Final model on all data (same code path as the app's first-run training)
    save_bundle(fit_bundle(X, Y, labels, smiles), MODEL_PATH)
    elapsed = time.time() - t0

    L = []
    w = L.append
    w("# Baseline: Morgan fingerprints + one-vs-rest logistic regression\n")
    w("Generated by `python scripts/run_baseline.py` "
      f"(seed={args.seed}, CPU only, total wall time {elapsed:.0f}s).\n")
    w("## Setup\n")
    w(f"- Features: Morgan fingerprint, radius {RADIUS}, {N_BITS} bits (RDKit), "
      "computed on `nonStereoSMILES`.")
    w(f"- Model: scikit-learn `OneVsRestClassifier(LogisticRegression(C={C}, "
      "class_weight='balanced', solver='liblinear'))` — one binary classifier per "
      f"label ({len(labels)} labels), each with per-label balanced class weights.")
    w("- Hyperparameters are fixed (sklearn default C); no tuning was done on any split.")
    w("- Macro ROC-AUC and mAP are computed over labels that have both positives "
      "and negatives in the evaluated test set; skipped labels are counted below. "
      "Macro F1 uses a fixed 0.5 threshold over all labels.\n")

    w(f"## (a) Stratified random {args.folds}-fold CV\n")
    w("Multi-label iterative stratification (Sechidis et al. 2011), implemented in "
      "`odormap/splits.py`. Molecules are split at random; scaffolds can be shared "
      "between train and test.\n")
    w("| Fold | n_train | n_test | " + " | ".join(METRICS) + " | labels skipped |")
    w("|---" * (len(METRICS) + 4) + "|")
    for k, r in enumerate(cv):
        w(f"| {k} | {r['n_train']} | {r['n_test']} | "
          + " | ".join(f"{r[m]:.4f}" for m in METRICS)
          + f" | {r['n_labels_skipped']} |")
    means = {m: np.mean([r[m] for r in cv]) for m in METRICS}
    stds = {m: np.std([r[m] for r in cv], ddof=1) for m in METRICS}
    w("| **mean ± sd** | | | "
      + " | ".join(f"**{means[m]:.4f} ± {stds[m]:.4f}**" for m in METRICS) + " | |\n")

    w(f"## (b) Bemis-Murcko scaffold split ({1 - args.test_frac:.0%}/{args.test_frac:.0%})\n")
    w("Molecules are grouped by Bemis-Murcko scaffold; whole groups are assigned to "
      "train or test so **no scaffold appears in both** (asserted in the script and "
      "in `tests/test_splits.py`). Groups are shuffled with the seed and filled into "
      "test up to the target size. The single largest group — the acyclic (empty) "
      "scaffold — is forced into train, so the scaffold test set contains **no acyclic "
      "molecules**; this is a property of this split, not just a leakage control, "
      "and makes the test distribution differ from the full dataset.\n")
    w("| Quantity | Value |\n|---|---|")
    w(f"| Train molecules | {len(tr)} |")
    w(f"| Test molecules | {len(te)} |")
    w(f"| Train scaffolds | {len(tr_sc)} |")
    w(f"| Test scaffolds | {len(te_sc)} |")
    w(f"| Shared scaffolds | {len(tr_sc & te_sc)} |")
    w(f"| Labels with no positives in test (skipped from macro AUC/mAP) | "
      f"{sc['n_labels_skipped']} |")
    te_counts = Counter(murcko_scaffold(smiles[i]) for i in te)
    top = ", ".join(f"`{k}` ({v})" for k, v in te_counts.most_common(5))
    w(f"| Largest test scaffold groups | {top} |\n")
    w("| Split | " + " | ".join(METRICS) + " |")
    w("|---" * (len(METRICS) + 1) + "|")
    w("| Random CV (mean) | " + " | ".join(f"{means[m]:.4f}" for m in METRICS) + " |")
    w("| Scaffold split | " + " | ".join(f"{sc[m]:.4f}" for m in METRICS) + " |\n")
    w("The scaffold-split numbers come from a single split (one seed) and so carry "
      "no variance estimate.\n")

    w("## Why is macro F1 low? (scaffold test set, measured)\n")
    w("Macro F1@0.5 is low on both splits. A common explanation is label imbalance "
      "(rare descriptors). We measured how per-label F1@0.5 on the scaffold test set "
      "relates to how many positives each label has, using Spearman rank correlation "
      f"over all {len(labels)} labels.\n")
    w("| Comparison (per label, n = labels) | Spearman ρ | p-value |\n|---|---|---|")
    w(f"| F1@0.5 vs # positives in the **test** set (n={len(labels)}) | "
      f"**{rho_te.statistic:.3f}** | {rho_te.pvalue:.1e} |")
    w(f"| F1@0.5 vs # positives in the **train** set (n={len(labels)}) | "
      f"{rho_tr.statistic:.3f} | {rho_tr.pvalue:.1e} |")
    w(f"| ROC-AUC vs # positives in the test set (n={int(ok.sum())}, context) | "
      f"{rho_auc.statistic:.3f} | {rho_auc.pvalue:.1e} |\n")
    w("| Test positives per label | Labels | Mean F1@0.5 |\n|---|---|---|")
    for lo, hi in bands:
        m = (pos_te >= lo) & (pos_te <= hi if hi else True)
        rng = f"{lo}–{hi}" if hi else f"≥ {lo}"
        w(f"| {rng} | {int(m.sum())} | {f1_lab[m].mean():.3f} |")
    w("")
    w(f"Macro precision@0.5 = {macro_p:.3f}, macro recall@0.5 = {macro_r:.3f}.\n")
    w("**What the data shows (measured):** per-label F1 is moderately, positively "
      f"rank-correlated with label frequency in the test set (ρ = {rho_te.statistic:.2f}) "
      f"and more weakly with frequency in the training set (ρ = {rho_tr.statistic:.2f}). "
      "So rarer labels do tend to have lower F1, but frequency explains only part of "
      "the variation, and the low F1 is not confined to rare labels: even labels with "
      "≥ 30 test positives average well below 0.5.\n")
    w("**What it does not show:** per-label ROC-AUC is essentially uncorrelated with "
      f"frequency (ρ = {rho_auc.statistic:.2f}), so rare labels are *ranked* about as "
      "well as common ones. Our hypothesis (not tested here) is that the F1–frequency "
      "association comes mostly from the fixed 0.5 threshold and prevalence: with few "
      "true positives, the same false-positive rate yields much lower precision, and "
      "labels with only a handful of test positives give very noisy F1. Low macro F1 "
      "should therefore not be read as simply \"caused by imbalance\": the untuned "
      "threshold and over-confident scores (see `results/calibration.md`) are "
      "plausible contributors too, and these factors have not been separated.\n")
    w("## Saved model\n")
    w(f"`models/baseline_lr.joblib` (git-ignored): the same model refit on all "
      f"{len(df)} molecules. Used by `scripts/predict.py`.")
    RESULTS.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(RESULTS.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
