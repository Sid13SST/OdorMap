"""Measure calibration of the baseline on the scaffold-split test set.

Fits the same model as scripts/run_baseline.py on the scaffold-split train set
(seed 0), scores the held-out scaffold test set, and writes
results/calibration.md and results/calibration_reliability.png.

ECE: 10 equal-width bins, (molecule, label) pairs pooled over labels with
at least MIN_POS positives in the test set.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from odormap.calibration import expected_calibration_error, reliability_bins  # noqa: E402
from odormap.data import REPO_ROOT, SMILES_COL, load_dataset  # noqa: E402
from odormap.features import featurize  # noqa: E402
from odormap.model import build_model  # noqa: E402
from odormap.splits import scaffold_split  # noqa: E402

OUT_MD = REPO_ROOT / "results" / "calibration.md"
OUT_PNG = REPO_ROOT / "results" / "calibration_reliability.png"
N_BINS = 10
MIN_POS = 30
BLUE, INK, MUTED = "#2a78d6", "#0b0b0b", "#52514e"


def plot(b, ece, n_labels, path):
    fig, (ax, axc) = plt.subplots(
        2, 1, figsize=(6, 6.4), sharex=True, gridspec_kw={"height_ratios": [3, 1]})
    for a in (ax, axc):
        a.spines[["top", "right"]].set_visible(False)
        a.tick_params(colors=MUTED)
        for sp in a.spines.values():
            sp.set_color("#c9c8c3")
    ax.plot([0, 1], [0, 1], ls="--", lw=1, color=MUTED, label="perfect calibration")
    ok = b["count"] > 0
    ax.plot(b["mean_score"][ok], b["frac_pos"][ok], "-o", lw=2, ms=7, color=BLUE,
            markeredgecolor="white", markeredgewidth=1.5, label="baseline (scaffold test)")
    ax.set_xlim(0, 1), ax.set_ylim(0, 1)
    ax.set_ylabel("Observed fraction positive", color=INK)
    ax.set_title(f"Reliability: pooled over {n_labels} labels (≥{MIN_POS} test positives)\n"
                 f"ECE ({N_BINS} bins) = {ece:.3f}", color=INK, fontsize=11)
    ax.grid(color="#ecebe7", lw=0.8)
    ax.legend(frameon=False, loc="upper left")
    centers = (b["edges"][:-1] + b["edges"][1:]) / 2
    axc.bar(centers, b["count"], width=0.1 - 0.008, color=BLUE)
    axc.set_yscale("log")
    axc.set_ylabel("Pairs per bin\n(log)", color=INK)
    axc.set_xlabel("Model score (bin)", color=INK)
    fig.tight_layout()
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--test-frac", type=float, default=0.2)
    args = p.parse_args(argv)

    df, labels = load_dataset()
    smiles = df[SMILES_COL].tolist()
    X, Y = featurize(smiles), df[labels].to_numpy()
    tr, te = scaffold_split(smiles, args.test_frac, args.seed)
    m = build_model().fit(X[tr], Y[tr])
    S, Yt = m.predict_proba(X[te]), Y[te]

    pos = Yt.sum(axis=0)
    keep = pos >= MIN_POS
    y_pool, s_pool = Yt[:, keep].ravel(), S[:, keep].ravel()
    b = reliability_bins(y_pool, s_pool, N_BINS)
    ece = expected_calibration_error(y_pool, s_pool, N_BINS)
    ece_all = expected_calibration_error(Yt.ravel(), S.ravel(), N_BINS)
    per_label = [expected_calibration_error(Yt[:, j], S[:, j], N_BINS)
                 for j in np.where(keep)[0]]
    plot(b, ece, int(keep.sum()), OUT_PNG)

    L = []
    w = L.append
    w("# Calibration of baseline scores (scaffold-split test set)\n")
    w("Generated by `python scripts/calibration.py` (seed="
      f"{args.seed}). Model: same Morgan-fingerprint + one-vs-rest logistic regression "
      "(`class_weight='balanced'`) as `results/baseline.md`, fit on the scaffold-split "
      f"train set ({len(tr)} molecules) and scored on the held-out scaffold test set "
      f"({len(te)} molecules, no acyclic molecules).\n")
    w("## Method\n")
    w(f"- Labels with ≥ {MIN_POS} positives in the test set: **{int(keep.sum())} of "
      f"{len(labels)}**.")
    w(f"- Every (test molecule, label) pair for those labels is pooled: "
      f"{len(y_pool):,} pairs, {int(y_pool.sum()):,} positive "
      f"(base rate {y_pool.mean():.3f}).")
    w(f"- {N_BINS} equal-width score bins on [0, 1]; "
      "ECE = Σ_b (n_b / N) · |observed positive fraction_b − mean score_b|.\n")
    w("## Result\n")
    w("| Quantity | Value |\n|---|---|")
    w(f"| **ECE, pooled, labels with ≥ {MIN_POS} test positives** | **{ece:.3f}** |")
    w(f"| Mean score vs observed positive rate (same pairs) | {s_pool.mean():.3f} vs "
      f"{y_pool.mean():.3f} |")
    w(f"| ECE, pooled over all {len(labels)} labels (context) | {ece_all:.3f} |")
    w(f"| Per-label ECE, median [min, max] over the {int(keep.sum())} labels (context) | "
      f"{np.median(per_label):.3f} [{min(per_label):.3f}, {max(per_label):.3f}] |\n")
    w("![Reliability curve](calibration_reliability.png)\n")
    w("| Score bin | Pairs | Mean score | Observed fraction positive | Gap |")
    w("|---|---|---|---|---|")
    for i in range(N_BINS):
        lo, hi = b["edges"][i], b["edges"][i + 1]
        if b["count"][i] == 0:
            w(f"| [{lo:.1f}, {hi:.1f}) | 0 | – | – | – |")
            continue
        ms, fp = b["mean_score"][i], b["frac_pos"][i]
        w(f"| [{lo:.1f}, {hi:.1f}{']' if i == N_BINS - 1 else ')'} | {b['count'][i]:,} | "
          f"{ms:.3f} | {fp:.3f} | {fp - ms:+.3f} |")
    w("")
    w("## Interpretation\n")
    ok = b["count"] > 0
    gaps = b["frac_pos"][ok] - b["mean_score"][ok]
    hi = b["edges"][:-1][ok] >= 0.5
    share_low = b["count"][0] / b["count"].sum()
    w(f"- Measured pooled ECE is {ece:.3f}. That single number looks modest mainly "
      f"because {share_low:.0%} of pairs fall in the lowest bin, where the gap is small. "
      f"In {int((gaps < 0).sum())} of {int(ok.sum())} bins the mean score exceeds the "
      "observed positive fraction (negative gap = over-confident).")
    w(f"- Over-confidence grows with score: in bins with score ≥ 0.5 the gap ranges "
      f"from {gaps[hi].max():+.3f} to {gaps[hi].min():+.3f}. For example, pairs scored "
      f"in [0.9, 1.0] are positive only {b['frac_pos'][-1]:.0%} of the time.")
    w("- A likely contributor (hypothesis, not tested here) is "
      "`class_weight='balanced'`, which trains each label as if it had a 50/50 class "
      "prior; the model was not trained or post-processed to produce calibrated "
      "probabilities.")
    w("- **Verdict:** treat outputs as **ranking scores (model confidence)**, not "
      "calibrated probabilities. A score of 0.8 does **not** mean an 80% chance the "
      "descriptor applies. Ranking quality is measured separately by ROC-AUC / mAP in "
      "`results/baseline.md`.")
    w("- Caveats: single scaffold split (one seed), so no variance estimate; the test "
      "set has no acyclic molecules (the acyclic scaffold group is forced into train); "
      "the saved app/CLI model is refit on all data and its calibration on new "
      "molecules is not directly measured here.")
    OUT_MD.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(OUT_MD.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
