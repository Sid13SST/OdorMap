"""Data audit: writes results/audit.md with measured numbers only."""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from odormap.data import REPO_ROOT, SMILES_COL, load_dataset  # noqa: E402
from odormap.features import canonical_smiles, murcko_scaffold, mol_from_smiles  # noqa: E402

OUT = REPO_ROOT / "results" / "audit.md"


def main() -> int:
    df, labels = load_dataset()
    smiles = df[SMILES_COL].tolist()
    n = len(df)

    mols = [mol_from_smiles(s) for s in smiles]
    invalid = [s for s, m in zip(smiles, mols) if m is None]
    valid_idx = [i for i, m in enumerate(mols) if m is not None]

    raw_dup = n - df[SMILES_COL].nunique()
    canon = [canonical_smiles(smiles[i]) for i in valid_idx]
    canon_counts = Counter(canon)
    dup_groups = {k: v for k, v in canon_counts.items() if v > 1}
    n_dup_rows = sum(v - 1 for v in dup_groups.values())

    Y = df[labels].to_numpy()
    freq = Y.sum(axis=0)
    per_mol = Y.sum(axis=1)
    order = np.argsort(-freq)
    zero_label_mols = int((per_mol == 0).sum())

    scaffolds = [murcko_scaffold(smiles[i]) for i in valid_idx]
    sc = Counter(scaffolds)
    sizes = np.array(sorted(sc.values(), reverse=True))
    singletons = int((sizes == 1).sum())
    mols_in_shared = int(sizes[sizes > 1].sum())

    L = []
    w = L.append
    w("# Data audit: curated_GS_LF_merged_4983.csv\n")
    w("Generated by `python scripts/audit.py`. All numbers measured on the fetched file; "
      "no conclusions are drawn beyond what the numbers show.\n")
    w("## Rows and SMILES validity\n")
    w("| Quantity | Value |\n|---|---|")
    w(f"| Total rows | {n} |")
    w(f"| Unparseable SMILES (RDKit) | {len(invalid)} |")
    w(f"| Duplicate raw SMILES strings (rows beyond first) | {raw_dup} |")
    w(f"| Unique canonical SMILES | {len(canon_counts)} |")
    w(f"| Duplicate canonical SMILES groups | {len(dup_groups)} |")
    w(f"| Rows that duplicate an earlier canonical SMILES | {n_dup_rows} |")
    if invalid:
        w("\nUnparseable SMILES:\n")
        for s in invalid:
            w(f"- `{s}`")
    if dup_groups:
        w("\nDuplicate canonical SMILES (count):\n")
        for k, v in sorted(dup_groups.items(), key=lambda kv: -kv[1])[:20]:
            w(f"- `{k}` x{v}")
    w("")

    w("## Labels\n")
    w("| Quantity | Value |\n|---|---|")
    w(f"| Label columns | {len(labels)} |")
    w(f"| Total positive (molecule, label) pairs | {int(Y.sum())} |")
    w(f"| Label density (positives / cells) | {Y.mean():.4f} |")
    w(f"| Labels per molecule: mean / median / min / max | "
      f"{per_mol.mean():.2f} / {np.median(per_mol):.0f} / {per_mol.min()} / {per_mol.max()} |")
    w(f"| Molecules with zero labels | {zero_label_mols} |")
    w(f"| Per-label positives: mean / median | {freq.mean():.1f} / {np.median(freq):.0f} |")
    w(f"| Per-label positives: min / max | {freq.min()} / {freq.max()} |")
    w(f"| Imbalance ratio (max / min label frequency) | {freq.max() / freq.min():.1f} |")
    for t in (20, 50, 100, 500):
        w(f"| Labels with < {t} positives | {int((freq < t).sum())} |")
    w("")
    w("### 15 most frequent labels\n")
    w("| Label | Positives | Prevalence |\n|---|---|---|")
    for j in order[:15]:
        w(f"| {labels[j]} | {freq[j]} | {freq[j] / n:.3f} |")
    w("\n### 15 least frequent labels\n")
    w("| Label | Positives | Prevalence |\n|---|---|---|")
    for j in order[::-1][:15]:
        w(f"| {labels[j]} | {freq[j]} | {freq[j] / n:.4f} |")
    w("\n<details><summary>All label frequencies</summary>\n")
    w("| Label | Positives |\n|---|---|")
    for j in order:
        w(f"| {labels[j]} | {freq[j]} |")
    w("\n</details>\n")

    w("## Bemis-Murcko scaffolds\n")
    w("| Quantity | Value |\n|---|---|")
    w(f"| Distinct scaffolds | {len(sc)} |")
    w(f"| Acyclic molecules (empty scaffold) | {sc.get('', 0)} |")
    w(f"| Scaffolds with exactly 1 molecule | {singletons} |")
    w(f"| Scaffolds shared by >= 2 molecules | {int((sizes > 1).sum())} |")
    w(f"| Molecules whose scaffold is shared with >= 1 other molecule | "
      f"{mols_in_shared} ({mols_in_shared / len(valid_idx):.1%}) |")
    w("")
    w("### Top 15 scaffold clusters\n")
    w("| Rank | Scaffold SMILES | Molecules |\n|---|---|---|")
    for r, (k, v) in enumerate(sc.most_common(15), 1):
        w(f"| {r} | `{k or '(acyclic)'}` | {v} |")
    w("")

    w("## Notes on interpretation\n")
    w("- The SMILES column is `nonStereoSMILES`: stereochemistry was removed upstream, so "
      "stereoisomers are not distinguishable in this file. The duplicate counts above are "
      "measured on these stereo-free strings.")
    w(f"- The two largest scaffold clusters (acyclic: {sc.get('', 0)}, `c1ccccc1`: "
      f"{sc.get('c1ccccc1', 0)}) together hold "
      f"{(sc.get('', 0) + sc.get('c1ccccc1', 0)) / len(valid_idx):.1%} of molecules. "
      "A Bemis-Murcko split treats all acyclic molecules as one group; see "
      "`results/baseline.md` for how the split handles it.\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(OUT.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
